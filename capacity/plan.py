"""Capacity plan: how many replicas / GPUs and what monthly cost for 100 / 10K / 1M daily users.

Method (the same arithmetic you'd do on a whiteboard):
  1. traffic:   peak req/s = DAU x requests/day / 86,400 x peak_to_average x (1 - cache hit rate)
  2. capacity:  per-replica req/s = MEASURED goodput (lowest of the listed runs), rescaled by answer
                length for other workloads (decode-bound: req/s ~ tokens/s / tokens per request)
  3. replicas:  needed = ceil(peak / (capacity x target utilization));  plan = max(min, needed + spare)
  4. cost:      plan x $/h x 730 h  (+ fixed platform cost);  "autoscaled" = replicas sized for the
                AVERAGE hour instead of the peak, as a lower bound for what an HPA could save

Usage: python capacity/plan.py            -> results/capacity_plan.csv + docs/CAPACITY_PLAN.md
"""
import math
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
A = yaml.safe_load(open(ROOT / "capacity/assumptions.yaml"))
P, T = A["planning"], A["traffic"]


def measured_capacity(hw: dict, runs: pd.DataFrame) -> dict:
    """Lowest goodput among the listed runs (conservative) and the answer length measured with it."""
    rows = []
    for r in hw["runs"]:
        m = runs[(runs["label"] == r["label"]) & (runs["users"] == r["users"])]
        rows.append(m)
    m = pd.concat(rows) if rows else pd.DataFrame()
    m = m[m["goodput_rps"] > 0]
    if m.empty:
        raise SystemExit(f"no measured runs found for {hw['name']}: {hw['runs']}")
    worst = m.loc[m["goodput_rps"].idxmin()]
    return {"rps": float(worst["goodput_rps"]), "rps_best": float(m["goodput_rps"].max()),
            "tok_per_req": float(worst["tokens_per_s"] / worst["throughput_rps"]),
            "tok_s": float(worst["tokens_per_s"] * worst["goodput_rps"] / worst["throughput_rps"]),
            "p95_s": float(worst["p95_s"]), "n_runs": len(m)}


def plan_rows(cap: dict) -> list[dict]:
    rows = []
    for wname, w in A["workloads"].items():
        out_tok = w["output_tokens"]
        for dau in T["tiers_dau"]:
            avg = dau * T["requests_per_dau_per_day"] / 86_400
            for hit in P["cache_hit_rates"]:
                peak = avg * T["peak_to_average"] * (1 - hit)
                mean = avg * (1 - hit)
                for hname, hw in A["hardware"].items():
                    c = cap[hname]
                    tok = out_tok or c["tok_per_req"]
                    per_replica = c["tok_s"] / tok                       # req/s per replica, this workload
                    usable = per_replica * P["target_utilization"]
                    needed = math.ceil(peak / usable) if peak > 0 else 0
                    replicas = max(P["min_replicas"], needed + P["spare_replicas"])
                    avg_replicas = max(P["min_replicas"], math.ceil(mean / usable) + P["spare_replicas"])
                    hourly = hw["usd_per_hour"]
                    compute = replicas * hourly * P["hours_per_month"]
                    reserved = (replicas * hw["usd_per_hour_reserved_1y"] * P["hours_per_month"]
                                if hw.get("usd_per_hour_reserved_1y") else None)
                    fixed = A["fixed_monthly_usd"]["kubernetes_control_plane"] + \
                        A["fixed_monthly_usd"]["redis"] * (2 if dau >= 1_000_000 else 1)
                    monthly_requests = dau * T["requests_per_dau_per_day"] * T["days_per_month"]
                    total = compute + fixed
                    rows.append({
                        "workload": wname, "dau": dau, "cache_hit_rate": hit,
                        "hardware": hname, "instance": hw["instance"],
                        "peak_rps": round(peak, 3), "per_replica_rps": round(per_replica, 2),
                        "replicas_needed": needed, "replicas_planned": replicas,
                        "replicas_autoscaled_avg_hour": avg_replicas,
                        "peak_utilization": round(peak / (replicas * per_replica), 3),
                        "compute_usd_month": round(compute), "compute_usd_month_reserved_1y":
                            round(reserved) if reserved else None,
                        "compute_usd_month_autoscaled": round(avg_replicas * hourly * P["hours_per_month"]),
                        "fixed_usd_month": round(fixed), "total_usd_month": round(total),
                        "usd_per_1k_requests": round(1000 * total / monthly_requests, 4),
                    })
    return rows


def money(x) -> str:
    return "—" if x is None or (isinstance(x, float) and math.isnan(x)) else f"${x:,.0f}"


def tier(dau: int) -> str:
    return {100: "100", 10_000: "10K", 1_000_000: "1M"}.get(dau, f"{dau:,}")


def markdown(df: pd.DataFrame, cap: dict) -> str:
    L = ["# Capacity plan: 100 / 10K / 1M daily users", "",
         "_Generated by `capacity/plan.py` from `capacity/assumptions.yaml` and the measured "
         "`results/loadtest_summary.csv`. Change an assumption and re-run; don't edit this file by hand._", "",
         "## 1. What was measured (per replica)", "",
         "| Hardware | Planned capacity (worst run) | Best run | Output tokens/request | p95 at that load |",
         "|---|---|---|---|---|"]
    for h, hw in A["hardware"].items():
        c = cap[h]
        L.append(f"| {hw['name']} | **{c['rps']:.2f} req/s** | {c['rps_best']:.2f} req/s | "
                 f"{c['tok_per_req']:.0f} | {c['p95_s']:.1f} s |")
    L += ["", "Capacity = goodput (answers within the 15 s SLO) at saturation, the **lowest** of the listed runs.",
          "Sessions varied by ~15% on the same hardware, so every number below has at least that much uncertainty.", "",
          "## 2. Assumptions", "",
          f"- **Traffic:** {T['requests_per_dau_per_day']} requests per daily user, busiest hour = "
          f"{T['peak_to_average']:.0f}x the daily average.",
          f"- **Headroom:** replicas run at {P['target_utilization']:.0%} of measured capacity at peak; "
          f"+{P['spare_replicas']} spare (N+1); never fewer than {P['min_replicas']}.",
          "- **Workloads:** " + "; ".join(f"`{k}` = {v['note']}" for k, v in A["workloads"].items()) + ".",
          "  The chat workload rescales measured throughput by answer length (decode-bound). Longer prompts cost "
          "extra prefill that this ignores, so treat chat numbers as **optimistic**.",
          "- **Prices:** AWS us-east-1 on-demand, Nov 2026 (c7i.xlarge $0.1785/h, g4dn.xlarge $0.526/h, "
          "EKS $73/mo, ElastiCache t4g.small $23/mo). Load balancer, data transfer, monitoring and people are **not** included.",
          "- **Model:** Qwen2.5-0.5B-Instruct, the model measured. A production assistant would use a 7-8B model, "
          "which changes every number below (see section 5).", ""]

    base = df[df["cache_hit_rate"] == 0]
    for wname in A["workloads"]:
        L += [f"## 3{'a' if wname == 'benchmark' else 'b'}. Plan, `{wname}` workload (no cache)", "",
              "| Daily users | Peak req/s | Hardware | Replicas (planned) | Utilization at peak | Compute/month | "
              "Autoscaled* | 1-yr reserved | Total/month | $ per 1K requests |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in base[base["workload"] == wname].iterrows():
            L.append(f"| {tier(r['dau'])} | {r['peak_rps']:.2f} | {r['instance']} | **{r['replicas_planned']}** "
                     f"({r['replicas_needed']} needed) | {r['peak_utilization']:.0%} | {money(r['compute_usd_month'])} | "
                     f"{money(r['compute_usd_month_autoscaled'])} | {money(r['compute_usd_month_reserved_1y'])} | "
                     f"**{money(r['total_usd_month'])}** | ${r['usd_per_1k_requests']:.3f} |")
        L += ["", "_*Autoscaled = replicas sized for the average hour instead of the peak: a lower bound on what an "
              "autoscaler could save (it ignores ramp-up time)._", ""]

    L += ["## 3c. What a 20% cache hit rate does (GPU, chat workload)", "",
          "| Daily users | No cache: replicas / cost | 20% hits: replicas / cost |", "|---|---|---|"]
    g = df[(df["hardware"] == "gpu_t4_vllm") & (df["workload"] == "chat")]
    for dau in T["tiers_dau"]:
        a = g[(g["dau"] == dau) & (g["cache_hit_rate"] == 0)].iloc[0]
        b = g[(g["dau"] == dau) & (g["cache_hit_rate"] == 0.2)].iloc[0]
        L.append(f"| {tier(dau)} | {a['replicas_planned']} / {money(a['total_usd_month'])} | "
                 f"{b['replicas_planned']} / {money(b['total_usd_month'])} |")
    L += ["", "Every cache hit is one request the GPUs never see, so the savings only show once there are enough "
          "replicas to remove one (here at 1M).", ""]
    L += [STATIC_TEXT]
    return "\n".join(L)


STATIC_TEXT = """## 4. Recommendation and bottleneck per tier

### 100 daily users (~0.04 req/s at peak)
- **Run:** 2 small replicas for availability, no Kubernetes. Docker Compose on two VMs, or a hosted API.
- **Bottleneck: not capacity.** One CPU replica could serve ~30x this traffic. What costs money is idle
  hardware and operating effort, and both scale with the *number* of things you run. (The table includes
  the $73 Kubernetes fee; two CPU VMs + Redis without Kubernetes are ~$284/month.)
- **User-visible issue: latency.** On CPU a single 50-token answer takes ~6 s (27 tokens/s). Streaming
  tokens as they're generated makes the wait feel much shorter (time-to-first-token < 1 s).

### 10K daily users (~3.5 req/s at peak)
- **Run:** CPU and GPU cost about the same **for short answers**; **for chat-length answers the GPU is
  ~4-5x cheaper**, and much faster per request. Choose by answer length, not by user count.
- **Bottleneck: per-replica throughput on CPU.** CPU replicas can't batch their way out: they're
  compute-bound from batch ~3 (Step 5). Scale-out must add real cores (Step 10: 3 replicas on 2 cores = 1 replica).
- **Watch:** admission settings must be re-derived for the replica size (Step 10's p50 15 s), and the
  cache's value depends on how many prompts actually repeat.

### 1M daily users (~350 req/s at peak)
- **Run:** a GPU fleet on Kubernetes. CPU would need hundreds of machines.
- **Bottleneck 1: GPU decode throughput and KV-cache memory.** Longer prompts or answers fill the KV cache
  and cut the batch size, so throughput drops with context length. Plan with your *real* token distribution.
- **Bottleneck 2: autoscaling lag.** A new GPU node takes minutes (node boot + multi-GB image + model load +
  warm-up), versus ~5 s for our small CPU pods. Keep headroom, scale on queue length/KV-cache usage (not CPU),
  and pre-scale for known peaks.
- **Bottleneck 3: the platform around the model.** Per-request load balancing (the sticky-connection trap,
  Step 10), Redis as a shared dependency (replicated, and the gateway already fails open), per-user rate
  limits, and multiple zones so one zone outage doesn't take everything down.
- **Cost levers, biggest first:** smaller or quantized model *if* quality holds (Step 7: check instruction
  following, not just accuracy), better GPU per dollar (measure it: L4/A10G/H100 with fast kernels),
  1-year reserved instances for the always-on base (~31% off) plus on-demand or spot for peaks, caching.

## 5. Caveats (what this plan does not know)
1. **Model size.** Everything was measured on a 0.5B model. A 7-8B model is ~15x larger: it needs a 24 GB+
   GPU (or 4-bit quantization), and per-GPU throughput drops by roughly an order of magnitude. Re-measure.
2. **Real traffic shape.** Requests per user, peak factor and answer length are assumptions. Measure them
   from logs, then update `capacity/assumptions.yaml`.
3. **One T4 type, one session at a time.** ~15% session variance; other GPUs weren't measured.
4. **Not included:** load balancer, data transfer, logging/monitoring, storage, staging environments, people.
"""


def main() -> None:
    runs = pd.read_csv(ROOT / "results/loadtest_summary.csv")
    cap = {h: measured_capacity(hw, runs) for h, hw in A["hardware"].items()}
    df = pd.DataFrame(plan_rows(cap))
    df.to_csv(ROOT / "results/capacity_plan.csv", index=False)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/CAPACITY_PLAN.md").write_text(markdown(df, cap))

    print("measured capacity per replica (worst of the listed runs):")
    for h, c in cap.items():
        print(f"  {h:<14} {c['rps']:7.2f} req/s  (best {c['rps_best']:.2f}, {c['n_runs']} runs) | "
              f"{c['tok_per_req']:.0f} output tokens/request | {c['tok_s']:.0f} output tokens/s")
    show = df[df["cache_hit_rate"] == 0][["workload", "dau", "hardware", "peak_rps", "per_replica_rps",
                                          "replicas_planned", "peak_utilization", "total_usd_month",
                                          "usd_per_1k_requests"]]
    print("\n" + show.to_string(index=False))
    print("\nsaved results/capacity_plan.csv and docs/CAPACITY_PLAN.md")


if __name__ == "__main__":
    main()
